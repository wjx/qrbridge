const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { Client } = require('@modelcontextprotocol/sdk/client/index.js')
const { StreamableHTTPClientTransport } = require('@modelcontextprotocol/sdk/client/streamableHttp.js')
const { ExecutionBridge } = require('../desktop/execution/bridge.cjs')
const { startMCP } = require('../desktop/execution/mcp.cjs')

test('official MCP client initializes, discovers tools, submits and queries; HTTP access is restricted', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'qrbridge-mcp-'))
  const bridge = new ExecutionBridge(dir); bridge.start(); bridge.targets = ['dev-server']
  const service = await startMCP(bridge, 0)
  t.after(async () => { await service.close(); fs.rmSync(dir, { recursive: true, force: true }) })
  const url = new URL(`http://127.0.0.1:${service.port}/mcp`)
  const headers = { Authorization: `Bearer ${bridge.config.token}` }
  assert.equal((await fetch(url, { method: 'POST', body: '{}' })).status, 401)
  assert.equal((await fetch(url, { headers: { ...headers, Origin: 'https://example.com' } })).status, 403)
  assert.equal((await fetch(url, { headers })).status, 405)
  assert.equal((await fetch(url, { method: 'POST', headers, body: 'x'.repeat(32769) })).status, 413)
  const client = new Client({ name: 'qrbridge-test', version: '1.0' })
  await client.connect(new StreamableHTTPClientTransport(url, { requestInit: { headers } }))
  t.after(() => client.close())
  assert.deepEqual((await client.listTools()).tools.map(t => t.name), ['ssh_targets', 'ssh_submit', 'ssh_status'])
  const targets = await client.callTool({ name: 'ssh_targets', arguments: {} })
  assert.deepEqual(JSON.parse(targets.content[0].text).targets, ['dev-server'])
  const args = { target: 'dev-server', command: 'hostname', requestId: 'mcp-retry' }
  const submit = await client.callTool({ name: 'ssh_submit', arguments: args })
  const job = JSON.parse(submit.content[0].text)
  assert.equal(job.state, 'queued')
  const retry = await client.callTool({ name: 'ssh_submit', arguments: args })
  assert.equal(JSON.parse(retry.content[0].text).jobId, job.jobId)
  const status = await client.callTool({ name: 'ssh_status', arguments: { jobId: job.jobId } })
  assert.equal(JSON.parse(status.content[0].text).command, 'hostname')
  const invalid = await client.callTool({ name: 'ssh_submit', arguments: { target: '-oProxyCommand=bad', command: 'id' } })
  assert.equal(invalid.isError, true)
  bridge.active = false
  assert.equal((await fetch(url, { method: 'POST', headers, body: '{}' })).status, 503)
})
